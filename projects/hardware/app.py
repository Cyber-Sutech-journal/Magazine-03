# ============================================================
# FLASK ROUTES
# ============================================================

@app.route('/')
def index():
    """
    Display the main web interface.
    """

    return render_template_string(HTML_PAGE)


@app.route('/status')
def status():
    """
    Return the current system status as JSON.
    """

    with lock:

        return jsonify({

            'mode':
                'Automatic' if auto_mode
                else 'Manual',

            'light':
                current_light,

            'brightness':
                current_brightness,

            'target':
                target_light,

            'led':
                led_enabled

        })


@app.route('/mode', methods=['POST'])
def change_mode():
    """
    Switch between automatic and manual modes.
    """

    global auto_mode
    global integral
    global previous_error

    data = request.get_json()

    mode = data.get('mode')

    with lock:

        if mode == 'auto':

            auto_mode = True

            # Reset PID terms when automatic mode starts.
            integral = 0
            previous_error = 0

        elif mode == 'manual':

            auto_mode = False

            # Apply manual brightness immediately.
            set_led_brightness(
                manual_brightness
            )

    return jsonify({

        'success': True

    })


@app.route('/led', methods=['POST'])
def control_led():
    """
    Enable or disable the LED.
    """

    global led_enabled

    data = request.get_json()

    state = data.get('enabled')

    with lock:

        led_enabled = bool(state)

        if not led_enabled:

            # Turn the LED completely off.
            set_led_brightness(0)

        else:

            # Restore manual brightness if manual mode is active.
            if not auto_mode:

                set_led_brightness(
                    manual_brightness
                )

    return jsonify({

        'success': True

    })


@app.route('/brightness', methods=['POST'])
def change_brightness():
    """
    Change the LED brightness used in manual mode.
    """

    global manual_brightness

    data = request.get_json()

    value = data.get('brightness')

    value = float(value)

    # Limit brightness to 0-100%.
    value = clamp(value, 0, 100)

    manual_brightness = value

    with lock:

        # Apply the new brightness immediately in manual mode.
        if not auto_mode:

            set_led_brightness(
                manual_brightness
            )

    return jsonify({

        'success': True

    })


@app.route('/target', methods=['POST'])
def change_target():
    """
    Change the desired ambient light level for automatic mode.
    """

    global target_light

    data = request.get_json()

    value = data.get('target')

    value = float(value)

    # Limit target light level to 0-100%.
    target_light = clamp(value, 0, 100)

    return jsonify({

        'success': True,

        'target':
            target_light

    })


